#!/usr/bin/env python3
"""Reference model for KEYCAPS.md 6.8 key translation plus 6.3 labels,
written separately from RawInput.cpp and CapLabeler.cpp.

Reads every KEY DOWN / KEY REPEAT event recorded by example-keyprobe
(tests/data/probe_keys.txt: key keycode modifiers isRepeat) and writes
tests/data/probe_keys.inc with the label each one should get in Symbols
mode, or DROP when the event makes no KeyStroke.

Python is only for producing test data; the tests never need it.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")

CTRL, ALT, SHIFT, CMD = "⌃", "⌥", "⇧", "⌘"

# GLFW keycodes of keys that are labelled by keycode.
SPECIAL_BY_CODE = {
    257: "↩", 335: "↩",  # Return, keypad Enter
    258: "⇥",                  # Tab
    32: "Space",
    259: "⌫",                  # Backspace
    261: "⌦",                  # Delete
    256: "⎋",                  # Esc
    263: "←", 262: "→", 265: "↑", 264: "↓",
    268: "Home", 269: "End", 266: "PgUp", 267: "PgDn",
}
for i in range(12):
    SPECIAL_BY_CODE[290 + i] = "F%d" % (i + 1)

MODIFIER_CODES = {340: SHIFT, 344: SHIFT, 341: CTRL, 345: CTRL,
                  342: ALT, 346: ALT, 343: CMD, 347: CMD}


def prefix(mods):
    # mods are oF bits: shift 1, control 2, alt 4, super 16
    return ((CTRL if mods & 2 else "") + (ALT if mods & 4 else "")
            + (SHIFT if mods & 1 else "") + (CMD if mods & 16 else ""))


def label(key, code, mods):
    if code == -1:
        return "DROP"
    if code in MODIFIER_CODES:
        return MODIFIER_CODES[code] if 0xE60 <= key <= 0xE67 else "DROP"
    if code == 280:
        return "⇪"
    if code in SPECIAL_BY_CODE:
        return prefix(mods) + SPECIAL_BY_CODE[code]
    if code == 260:
        return "DROP"
    if mods & (2 | 4):
        if not (33 <= code <= 96 or code in (161, 162)):
            return "DROP"
        return prefix(mods) + chr(code).upper()
    if key < 32 or key == 127 or 0xE000 <= key <= 0xF8FF:
        return "DROP"
    if mods & 16:
        return prefix(mods) + chr(key).upper()
    return chr(key)


def c_escape(s):
    return "".join(c if 32 <= ord(c) < 127 and c not in '\\"' else
                   "".join("\\x%02X" % b for b in c.encode("utf-8")) + '""'
                   for c in s)


def main():
    rows = []
    with open(os.path.join(DATA, "probe_keys.txt")) as f:
        for line in f:
            k, c, m, r = (int(x) for x in line.split())
            rows.append((k, c, m, r, label(k, c, m)))
    out = [
        "// Generated by tests/reference/key_reference.py from",
        "// tests/data/probe_keys.txt (example-keyprobe passes 1 to 3).",
        "// Do not edit by hand.",
        "",
        "struct RecordedKey { int key; int keycode; int modifiers; bool isRepeat; const char * label; };",
        "static const RecordedKey kProbeKeys[] = {",
    ]
    for k, c, m, r, lab in rows:
        out.append('\t{ %d, %d, %d, %s, "%s" },' % (k, c, m, "true" if r else "false", c_escape(lab)))
    out.append("};")
    with open(os.path.join(DATA, "probe_keys.inc"), "w") as f:
        f.write("\n".join(out) + "\n")
    seen = []
    for row in rows:
        if row[4] not in seen:
            seen.append(row[4])
    print("events=%d distinct labels=%d" % (len(rows), len(seen)))
    print(" ".join(seen))


if __name__ == "__main__":
    main()
