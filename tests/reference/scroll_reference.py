#!/usr/bin/env python3
"""Reference model for KEYCAPS.md M6 (scroll gestures), written separately
from the C++ so the two can check each other.

Reads the scroll events recorded by example-keyprobe pass 1 (time, scrollX,
scrollY), groups them into gestures, and writes tests/data/probe_pass1_scroll.inc:
the events as a C array, and the visible gestures this model expects.

Formulation differs from ScrollGesture.cpp on purpose: gestures are found in
two passes (split the whole stream at gaps first, then split each run at
reversals), using the product test v * s < 0 rather than comparing signs.

Python is only for producing and checking test data. Nothing in the addon
or its tests needs Python to run.
"""
import os
import sys

SCROLL_GAP = 0.3
SCROLL_MIN = 1.0

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")


def load(path):
    events = []
    with open(path) as f:
        for line in f:
            t, x, y = line.split()
            events.append((float(t), float(x), float(y)))
    return events


def split_at_gaps(events):
    runs, run = [], []
    for e in events:
        if run and e[0] - run[-1][0] > SCROLL_GAP:
            runs.append(run)
            run = []
        run.append(e)
    if run:
        runs.append(run)
    return runs


def dominant(sx, sy):
    """('y', sum) when the vertical sum is at least as large, else ('x', sum)."""
    return ("y", sy) if abs(sy) >= abs(sx) else ("x", sx)


def split_at_reversals(run):
    gestures, cur, sx, sy = [], [], 0.0, 0.0
    for e in run:
        _, x, y = e
        if cur:
            axis, s = dominant(sx, sy)
            v = y if axis == "y" else x
            if v * s < 0:
                gestures.append(cur)
                cur, sx, sy = [], 0.0, 0.0
        cur.append(e)
        sx += x
        sy += y
    if cur:
        gestures.append(cur)
    return gestures


def direction(sx, sy):
    axis, s = dominant(sx, sy)
    if axis == "y":
        return "Down" if s < 0 else "Up"
    return "Right" if s < 0 else "Left"


def visible_gestures(events):
    out = []
    for run in split_at_gaps(events):
        for g in split_at_reversals(run):
            sx = sy = 0.0
            for i, (t, x, y) in enumerate(g):
                sx += x
                sy += y
                if max(abs(sx), abs(sy)) >= SCROLL_MIN:
                    out.append({
                        "start": g[0][0],
                        "visibleAt": t,
                        "visibleIndex": i,
                        "events": len(g),
                        "dirAtVisible": direction(sx, sy),
                    })
                    break
    return out


def main():
    events = load(os.path.join(DATA, "probe_pass1_scroll.txt"))
    gestures = visible_gestures(events)
    lines = [
        "// Generated by tests/reference/scroll_reference.py from",
        "// tests/data/probe_pass1_scroll.txt (example-keyprobe pass 1).",
        "// Do not edit by hand.",
        "",
        "struct RecordedScroll { double t; float x; float y; };",
        "static const RecordedScroll kPass1Scroll[] = {",
    ]
    for t, x, y in events:
        lines.append("\t{ %.3f, %.3ff, %.3ff }," % (t, x, y))
    lines += [
        "};",
        "",
        "struct ExpectedGesture { double start; double visibleAt; const char * dir; };",
        "static const ExpectedGesture kPass1Expected[] = {",
    ]
    for g in gestures:
        lines.append('\t{ %.3f, %.3f, "%s" },' % (g["start"], g["visibleAt"], g["dirAtVisible"]))
    lines.append("};")
    out = os.path.join(DATA, "probe_pass1_scroll.inc")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("events=%d visible_gestures=%d" % (len(events), len(gestures)))
    for g in gestures:
        print("  start=%.3f visibleAt=%.3f events=%d dir=%s" % (
            g["start"], g["visibleAt"], g["events"], g["dirAtVisible"]))


if __name__ == "__main__":
    sys.exit(main())
